import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { test } from 'node:test';
import { install, cleanup, aquila, editConfig, project, readIn } from './helpers.mjs';

const pkg = (react = false) =>
  JSON.stringify({
    name: 'synthetic-aquila-project',
    ...(react ? { dependencies: { react: '19' } } : {}),
    scripts: { test: 'node --test', typecheck: 'node --check src/app.js' },
  });
const fixtures = {
  node: { 'package.json': pkg(), 'src/app.js': 'export const value = 1;\n' },
  'node-react': { 'package.json': pkg(true), 'src/app.js': 'export const value = 1;\n' },
};

test('scenarios: with/without React × two modes × four tool choices', async (t) => {
  for (const [fixture, files] of Object.entries(fixtures)) {
    for (const mode of ['local', 'team']) {
      for (const tools of ['codex', 'copilot', 'claude', 'copilot,claude,codex']) {
        await t.test(`${fixture} / ${mode} / ${tools}`, () => {
          const root = project(
            { ...files, 'README.md': '# Existing team documentation\n' },
            { node: false },
          );
          try {
            install(root);
            const args = [
              '--lang=en',
              `--mode=${mode}`,
              `--tools=${tools}`,
              '--lint=off',
              '--token-limit=none',
            ];
            const init = aquila(root, 'init', ...args);
            assert.equal(init.code, 0, init.out);
            const cfg = JSON.parse(readIn(root, 'docs/ai/aquila.json'));
            assert.equal(cfg.stack, 'node-react');
            assert.equal(/react not found/.test(init.out), fixture === 'node');
            assert.equal(cfg.mode, mode);
            assert.deepEqual(cfg.tools, tools.split(','));
            assert.equal(readIn(root, 'README.md'), '# Existing team documentation\n');
            assert.equal(existsSync(join(root, 'CLAUDE.md')), tools.includes('claude'));
            assert.equal(
              existsSync(join(root, '.github/copilot-instructions.md')),
              tools.includes('copilot'),
            );
            assert.ok(existsSync(join(root, '.github/workflows/aquila-gates.yml')));
            const first = readIn(root, 'AGENTS.md');
            assert.equal(aquila(root, 'check').code, 0);
            const sync = aquila(root, 'sync');
            assert.equal(sync.code, 0, sync.out);
            assert.match(sync.out, /already in sync/);
            const again = aquila(root, 'init', ...args);
            assert.equal(again.code, 0, again.out);
            assert.equal(readIn(root, 'AGENTS.md'), first);
            assert.deepEqual(JSON.parse(readIn(root, 'docs/ai/aquila.json')), cfg);
            editConfig(root, (config) => {
              config.gates = { smoke: 'node -e "process.exit(0)"' };
              config.hooks = { ci: ['smoke'], 'pre-commit': [], 'pre-push': ['smoke'] };
            });
            const gate = aquila(root, 'gate', 'ci');
            assert.equal(gate.code, 0, gate.out);
            assert.match(gate.out, /1\/1 gates green/);
          } finally {
            cleanup(root);
          }
        });
      }
    }
  }
});

test('scenarios: local/team and tool transitions preserve team content', () => {
  const root = project({ 'AGENTS.md': '# Team rules\n', 'CLAUDE.md': '# Claude notes\n' });
  try {
    install(root);
    aquila(root, 'init', '--tools=codex', '--mode=local', '--lint=off');
    for (const [mode, tools] of [
      ['team', 'copilot,claude,codex'],
      ['team', 'copilot'],
      ['local', 'codex'],
      ['team', 'claude'],
    ]) {
      const result = aquila(root, 'init', `--mode=${mode}`, `--tools=${tools}`, '--lint=off');
      assert.equal(result.code, 0, result.out);
      assert.ok(readIn(root, 'AGENTS.md').endsWith('# Team rules\n'));
      assert.ok(readIn(root, 'CLAUDE.md').endsWith('# Claude notes\n'));
      assert.equal(
        readIn(root, 'CLAUDE.md').includes('generated by aquila-react-ai'),
        tools.includes('claude'),
      );
      assert.equal(aquila(root, 'check').code, 0);
      assert.match(aquila(root, 'sync').out, /already in sync/);
    }
  } finally {
    cleanup(root);
  }
});

test('scenarios: every invalid init flag fails before creating configuration', () => {
  const root = project();
  try {
    for (const flag of [
      '--lang=invalid',
      '--mode=invalid',
      '--tools=unknown',
      '--tools=codex,codex',
      '--lint=invalid',
      '--token-limit=-1',
      '--token-limit=Infinity',
      '--pr-max-files=0',
      '--unknown=value',
    ]) {
      const result = aquila(root, 'init', flag);
      assert.equal(result.code, 1, `${flag}: ${result.out}`);
      assert.ok(!existsSync(join(root, 'docs/ai/aquila.json')), flag);
      assert.ok(!existsSync(join(root, 'AGENTS.md')), flag);
    }
  } finally {
    cleanup(root);
  }
});

test('scenarios: invalid config blocks check and can be recovered without losing docs', () => {
  const root = project();
  try {
    aquila(root, 'init', '--tools=codex', '--lint=off');
    const config = readIn(root, 'docs/ai/aquila.json');
    writeFileSync(join(root, 'docs/ai/CONTEXT.md'), '# Context from the team\n');
    for (const invalid of ['null', '[]', '{}', '{', '{"version":99}']) {
      writeFileSync(join(root, 'docs/ai/aquila.json'), invalid);
      const result = aquila(root, 'check', '--ready');
      assert.equal(result.code, 1, invalid);
      assert.doesNotMatch(result.out, /technical readiness verified/);
      assert.equal(readIn(root, 'docs/ai/CONTEXT.md'), '# Context from the team\n');
    }
    writeFileSync(join(root, 'docs/ai/aquila.json'), config);
    assert.equal(aquila(root, 'sync').code, 0);
    assert.equal(aquila(root, 'check').code, 0);
  } finally {
    cleanup(root);
  }
});

test('scenarios: failed gates do not prevent collecting the remaining gates results', () => {
  const root = project();
  try {
    aquila(root, 'init', '--tools=codex', '--lint=off');
    editConfig(root, (cfg) => {
      cfg.gates = {
        fail: 'node -e "console.log(\'fixture failure\'); process.exit(9)"',
        pass: 'node -e "console.log(\'fixture success\')"',
      };
      cfg.hooks = { ci: ['fail', 'pass'] };
    });
    const result = aquila(root, 'gate', 'ci');
    assert.equal(result.code, 1);
    assert.match(result.out, /fixture failure/);
    assert.match(result.out, /✓ pass/);
    assert.match(result.out, /1\/2 gates green/);
  } finally {
    cleanup(root);
  }
});

test('scenarios: versioned instructions are not silently replaced in local mode', () => {
  const root = project({ 'AGENTS.md': '# Versioned team rules\n' });
  try {
    execFileSync('git', ['add', 'AGENTS.md'], { cwd: root });
    const before = readFileSync(join(root, 'AGENTS.md'));
    const result = aquila(root, 'init', '--mode=local', '--tools=codex', '--lint=off');
    assert.equal(result.code, 0);
    assert.match(result.out, /versioned.*local mode/);
    assert.deepEqual(readFileSync(join(root, 'AGENTS.md')), before);
    const ready = aquila(root, 'check', '--ready');
    assert.equal(ready.code, 1);
    assert.match(ready.out, /AGENTS\.md without the aquila-react-ai block/);
  } finally {
    cleanup(root);
  }
});
