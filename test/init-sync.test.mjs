test('tokens: per-scope estimate, alert above 20% of the limit, no limit means no alert', () => {
  const root = project({ 'src/a.ts': 'x'.repeat(4000), 'src/logo.png': 'y'.repeat(99999) });
  try {
    git(root, 'add', '-A');
    aquila(root, 'init', '--token-limit=10000');
    assert.equal(JSON.parse(readIn(root, 'docs/ai/aquila.local.json')).tokenLimit, 10000);
    assert.match(
      readIn(root, '.git/info/exclude'),
      /^\/docs\/ai\/aquila\.local\.json$/m,
      "it is the dev's",
    );
    // 4000 chars / 4 × 2 = 2000 tokens = 20%: at the limit, no alert yet; the .png does not count.
    const scoped = aquila(root, 'tokens', 'src');
    assert.match(scoped.out, /~2000 estimated tokens \(1 files\) = 20\.0% of the monthly limit/);
    assert.doesNotMatch(scoped.out, /ALERT/);
    writeFileSync(join(root, 'src/b.ts'), 'z');
    git(root, 'add', '-A');
    assert.match(aquila(root, 'tokens', 'src').out, /! ALERT: above 20% of the monthly limit/);
    assert.match(aquila(root, 'doctor').out, /monthly token limit 10000/);

    aquila(root, 'init', '--token-limit=none');
    const none = aquila(root, 'tokens');
    assert.match(none.out, /no monthly limit set: no alert/);
    assert.doesNotMatch(none.out, /ALERT/);
  } finally {
    cleanup(root);
  }
});

test('CI workflow: sync regenerates it from aquila.json → ci and check fails if it drifts', () => {
  const root = project();
  try {
    install(root);
    aquila(root, 'init');
    const fresh = readIn(root, CALLER);
    assert.match(fresh, /^# Generated by `npx aquila-react-ai sync`/);
    assert.match(fresh, /run: npx aquila-react-ai check\n/);
    assert.match(fresh, /run: npx aquila-react-ai gate ci\n/);
    assert.doesNotMatch(fresh, /gates\.yml@|submodule|secrets\.|uses: .*aquila/i);
    // Old header and stale content: check flags it, sync fixes it.
    writeFileSync(
      join(root, CALLER),
      fresh.replace('aquila-react-ai sync`', 'aquila-react-ai init`').replace("'22'", "'20'"),
    );
    const stale = aquila(root, 'check');
    assert.equal(stale.code, 1, stale.out);
    assert.match(stale.out, /aquila-gates\.yml out of date/);
    aquila(root, 'sync');
    assert.equal(readIn(root, CALLER), fresh);
    assert.equal(aquila(root, 'check').code, 0);
    editConfig(root, (cfg) => (cfg.ci['node-version'] = '24'));
    assert.match(aquila(root, 'check').out, /aquila-gates\.yml out of date/);
    aquila(root, 'sync');
    assert.match(readIn(root, CALLER), /node-version: '24'/);
    assert.equal(git(root, 'check-ignore', '--no-index', CALLER), '', 'versioned, never excluded');
    // Hand-written workflow (no header): not aquila-react-ai's, left intact.
    writeFileSync(join(root, CALLER), 'name: my-ci\n');
    assert.match(aquila(root, 'sync').out, /aquila-gates\.yml exists and was not generated/);
    assert.equal(readIn(root, CALLER), 'name: my-ci\n');
  } finally {
    cleanup(root);
  }
});

