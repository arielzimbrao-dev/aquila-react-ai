const USAGE = `usage: npx aquila-react-ai <command>
  init [--lang=en|pt-BR|pt-PT] [--tools=copilot,claude,codex] [--token-limit=<n>|none] [--mode=local|team] [--lint=off|standard|high] [--pr-max-files=<n>]
  sync | check [--ready] | doctor | gate <pre-commit|pre-push|ci>
  lint [rules|matrix] [--level=off|standard|high] | tokens [paths…] | --version`;

const isMain = process.argv[1] && realpathSync(process.argv[1]) === realpathSync(SELF);
if (isMain) {
  if (!nodeVersionSupported()) {
    console.error(`✗ aquila-react-ai requires Node ≥ 22; current version: ${process.versions.node}`);
    process.exit(1);
  }
  const [cmd, ...args] = process.argv.slice(2);
  const commands = {
    init: () => init(parseOpts(args)),
    sync: () => (console.log(sync().join('\n') || '✓ adapters already in sync'), 0),
    check: () => check(args),
    doctor,
    gate: () => {
      if (args.length > 1) throw new Error('gate arguments: accepts a single phase');
      return gate(args[0] ?? 'ci');
    },
    tokens: () => tokens(args),
    lint: () => lint(args),
    '--version': () => (console.log(version()), 0),
  };
  if (!commands[cmd]) {
    console.log(USAGE);
    process.exit(cmd && !['help', '--help', '-h'].includes(cmd) ? 1 : 0);
  }
  try {
    process.exit(await commands[cmd]());
  } catch (error) {
    console.error(`✗ ${error.message}`);
    process.exit(1);
  }
}
