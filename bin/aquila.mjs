const TOOL_MISSING = /not recognized|command not found|ENOENT|npx canceled/i;

function ciChangedFiles() {
  const eventPath = process.env.GITHUB_EVENT_PATH;
  if (!eventPath || !existsSync(eventPath))
    return { files: null, reason: 'GitHub event payload unavailable' };

  let event;
  try {
    event = JSON.parse(readFileSync(eventPath, 'utf8'));
  } catch (error) {
    return { files: null, reason: `invalid GitHub event payload: ${error.message}` };
  }
  if (!event || typeof event !== 'object')
    return { files: null, reason: 'GitHub event payload is not an object' };
  const pullRequest = event.pull_request;
  const base = pullRequest?.base?.sha ?? event.before;
  const head = process.env.GITHUB_SHA ?? event.after ?? pullRequest?.head?.sha;
  if (
    typeof base !== 'string' ||
    typeof head !== 'string' ||
    !/^[0-9a-f]{40,64}$/i.test(base) ||
    !/^[0-9a-f]{40,64}$/i.test(head) ||
    /^0+$/.test(base)
  ) {
    return { files: null, reason: 'the event has no comparable base/head commits' };
  }

  const range = pullRequest ? `${base}...${head}` : `${base}..${head}`;
  // --relative: `when` globs are the project's (src/**), and in a subfolder git would print frontend/src/….
  const result = spawnSync('git', ['diff', '--name-only', '-z', '--no-renames', '--relative', range], {
    cwd: ROOT,
    encoding: 'utf8',
  });
  if (result.status !== 0)
    return {
      files: null,
      reason: `git diff failed: ${(result.stderr || result.error?.message || '').trim()}`,
    };
  return { files: result.stdout.split('\0').filter(Boolean).map(posix) };
}

export function gate(phase) {
  if (!['ci', 'pre-commit', 'pre-push'].includes(phase))
    throw new Error(`invalid phase: ${phase} (valid: pre-commit, pre-push, ci)`);
  const cfg = loadConfig();
  const names =
    phase === 'ci' ? (cfg.hooks?.ci ?? Object.keys(cfg.gates)) : (cfg.hooks?.[phase] ?? []);
  if (!names.length) {
    // An empty local hook is the project's choice; in CI a "0/0 green" would be a gate that checks nothing.
    const ci = phase === 'ci';
    log(
      !ci,
      `no gates in phase ${phase} (${CONFIG} → hooks.${phase})${ci ? ' — CI cannot pass without checking anything' : ''}`,
    );
    return ci ? 1 : 0;
  }
  const hasConditionalGates =
    phase === 'ci' &&
    names.some((name) => cfg.gates?.[name] && Array.isArray(cfg.gates[name].when));
  const changes = hasConditionalGates ? ciChangedFiles() : null;
  if (changes && !changes.files)
    console.log(
      `! could not determine changed files (${changes.reason}); conditional gates run to be safe`,
    );
  let failed = 0;
  let skipped = 0;
  for (const name of names) {
    const spec = cfg.gates[name];
    if (!spec) {
      log(false, `${name}: gate not defined in ${CONFIG}`);
      failed++;
      continue;
    }
    if (
      Array.isArray(spec.when) &&
      (!spec.when.length ||
        spec.when.some((pattern) => typeof pattern !== 'string' || !pattern.trim()))
    ) {
      log(false, `${name}: when must contain non-empty path globs`);
      failed++;
      continue;
    }
    if (changes?.files && Array.isArray(spec.when)) {
      const patterns = spec.when.map(globToRegex);
      if (!changes.files.some((file) => patterns.some((pattern) => pattern.test(file)))) {
        console.log(`↷ ${name}: no changed file matches ${spec.when.join(', ')}`);
        skipped++;
        continue;
      }
    }
    const cmd = typeof spec === 'string' ? spec : spec.cmd;
    const started = Date.now();
    const r = spawnSync(cmd, {
      cwd: ROOT,
      shell: true,
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
    });
    const secs = ((Date.now() - started) / 1000).toFixed(1);
    if (r.status === 0) {
      log(true, `${name} (${secs}s)`);
      continue;
    }
    failed++;
    log(false, `${name} (${secs}s): ${cmd}`);
    const output = `${r.stdout ?? ''}${r.stderr ?? ''}`.trim();
    const tail = output.split('\n').slice(-40).join('\n');
    if (tail) console.log(tail.replace(/^/gm, '  '));
    if (r.status === 127 || TOOL_MISSING.test(output)) {
      console.log(
        `  → this gate's tool seems not to be installed; install it or adjust gates.${name} in ${CONFIG}`,
      );
    }
  }
  const executed = names.length - skipped;
  console.log(
    `${executed - failed}/${executed} gates green (${phase})${skipped ? `; ${skipped} skipped` : ''}`,
  );
  return failed ? 1 : 0;
}

// ---------------------------------------------------------------- tokens

/** Above this share of the dev's monthly limit, a command asks for approval (core/tokens.md). */
export const TOKEN_ALERT = 0.2;
// Not text: an agent doesn't read it.
const NOT_TEXT =
  /\.(png|jpe?g|gif|ico|webp|pdf|zip|gz|woff2?|ttf|eot|exe|dll|so|dylib|bin)$|(^|\/)(package-lock\.json|pnpm-lock\.yaml|yarn\.lock)$|^\.aquila\//i;

/**
 * Tokens an agent spends reading the versioned files in `paths` (everything, if empty).
 * ponytail: ~4 chars per token × 2 (re-reads, output, tools) — rough estimate; tune the multiplier
 * against real measured usage.
 */
export function estimateTokens(paths = []) {
  const files = git('ls-files', '-z', '--', ...paths)
    .split('\0')
    .filter((f) => f && !NOT_TEXT.test(f) && existsSync(p(f)) && statSync(p(f)).isFile());
  const bytes = files.reduce((sum, f) => sum + statSync(p(f)).size, 0);
  return { files: files.length, tokens: Math.round((bytes / 4) * 2) };
}

const tokenLimit = () => (existsSync(p(LOCAL)) ? readJson(LOCAL).tokenLimit : null) ?? null;

export function tokens(args) {
  const { files, tokens: n } = estimateTokens(args.filter((a) => !a.startsWith('--')));
  const limit = tokenLimit();
  const share = limit ? n / limit : 0;
  const of = limit
    ? ` = ${(share * 100).toFixed(1)}% of the monthly limit (${limit})`
    : ' · no monthly limit set: no alert';
  console.log(`~${n} estimated tokens (${files} files)${of}`);
  if (share > TOKEN_ALERT)
    console.log(
      `! ALERT: above ${TOKEN_ALERT * 100}% of the monthly limit — ask the dev for approval before continuing (or narrow the scope)`,
    );
  return 0;
}

