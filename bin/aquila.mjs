/**
 * The invariants/architectural rules section of CONTEXT.md (heading containing one of
 * `review.contextSections`), with relative links rewritten for `.github/`.
 */
function contextSection(cfg) {
  if (!existsSync(p('docs/ai/CONTEXT.md'))) return '';
  const names = cfg.review?.contextSections ?? ['invariant', 'architectural rules'];
  const lines = lf(read('docs/ai/CONTEXT.md')).split('\n');
  const start = lines.findIndex(
    (l) => /^#{2,3} /.test(l) && names.some((n) => l.toLowerCase().includes(n.toLowerCase())),
  );
  if (start < 0) return '';
  const depth = /^#+/.exec(lines[start])[0].length;
  const stop = lines.findIndex((l, i) => i > start && new RegExp(`^#{1,${depth}} `).test(l));
  const text = lines
    .slice(start + 1, stop < 0 ? undefined : stop)
    .join('\n')
    .trim();
  return text.replaceAll(/\]\(([^)\s]+)\)/g, (whole, target) => {
    if (/^(?:[a-z][a-z0-9+.-]*:|#)/i.test(target)) return whole;
    const [path, anchor] = target.split('#');
    const rel = posixPath.relative('.github', posixPath.join('docs/ai', path));
    return `](${rel}${anchor === undefined ? '' : `#${anchor}`})`;
  });
}

