/** [path inside .aquila, content] for every method file. */
function methodFiles() {
  const list = (rel) =>
    statSync(join(PKG, rel)).isDirectory()
      ? readdirSync(join(PKG, rel)).flatMap((n) => list(posix(join(rel, n))))
      : [rel];
  const readme = [
    `# .aquila — aquila-react-ai ${version()}`,
    '',
    'Generated by `npx aquila-react-ai sync` from the installed package: do not edit, commit it.',
    'Agents (local and cloud) read the method from here. Update: `npm i -D aquila-react-ai@latest && npx aquila-react-ai sync`.',
    '',
  ].join('\n');
  return [
    ...METHOD_ITEMS.flatMap(list).map((rel) => [rel, readFileSync(join(PKG, rel), 'utf8')]),
    ['README.md', readme],
  ];
}

const listMethod = (dir = METHOD) =>
  existsSync(p(dir))
    ? readdirSync(p(dir)).flatMap((n) => {
        const rel = posix(join(dir, n));
        return statSync(p(rel)).isDirectory() ? listMethod(rel) : [rel];
      })
    : [];

/** Files in .aquila/ that differ from the installed package (CRLF is no difference). */
function methodDrift() {
  const want = new Map(methodFiles().map(([rel, text]) => [`${METHOD}/${rel}`, text]));
  const drift = [...want]
    .filter(([path, text]) => !existsSync(p(path)) || lf(read(path)) !== lf(text))
    .map(([path]) => `${path} out of date`);
  for (const path of listMethod().filter((f) => !want.has(f)))
    drift.push(`${path} not in aquila-react-ai ${version()}`);
  return drift.length > 5 ? [...drift.slice(0, 5), `… ${drift.length - 5} more in ${METHOD}/`] : drift;
}

/** Registry lines as [package, dir], comments and blanks dropped. */
function readRegistry(place) {
  const file = atTop(place, REGISTRY);
  if (!existsSync(file)) return [];
  return readFileSync(file, 'utf8')
    .split(/\r?\n/)
    .filter((line) => line.trim() && !line.startsWith('#'))
    .map((line) => {
      const [pkg, ...dir] = line.trim().split(/\s+/);
      return [pkg, dir.join(' ') || '.'];
    });
}

/**
 * The repository's shared hook dispatcher and this project's line in the registry. Rewrites only aquila-hooks
 * v1 copies (identical in every aquila package); a newer version or a hand-written hook stays. Also moves a
 * 0.1.0 core.hooksPath (resolved from the root, so broken in a subfolder) to the dispatcher.
 */
function syncHooks() {
  const place = repoPlace();
  if (!place) return [];
  const notes = [];
  const source = readFileSync(join(PKG, 'githooks', 'pre-commit'), 'utf8');
  const files = [
    ['pre-commit', source, true],
    ['pre-push', source, true],
    // Keeps the hooks LF on Windows checkouts with autocrlf (sh breaks with CRLF).
    ['.gitattributes', '* text eol=lf\n', false],
  ];
  for (const [name, content, exec] of files) {
    const file = atTop(place, DISPATCH, name);
    const current = existsSync(file) ? lf(readFileSync(file, 'utf8')) : null;
    if (current !== content) {
      const version = current === null ? 0 : Number(DISPATCH_VERSION.exec(current)?.[1] ?? NaN);
      if (exec && !(version <= 1)) {
        if (Number.isNaN(version))
          notes.push(`! ${DISPATCH}/${name} is not an aquila-hooks dispatcher — left untouched`);
        continue;
      }
      if (!exec && current !== null) continue;
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, content);
      notes.push(`✓ ${DISPATCH}/${name} (repository root; commit it)`);
    }
    if (exec) chmodSync(file, 0o755);
  }
  // Each package keeps the other packages' lines; lines of projects that no longer exist leave.
  const lines = readRegistry(place).filter(
    ([, dir]) => dir !== place.dir && existsSync(atTop(place, dir, CONFIG)),
  );
  lines.push([PACKAGE, place.dir]);
  lines.sort((a, b) => a[1].localeCompare(b[1]));
  const registry = `${REGISTRY_HEADER}${lines.map((l) => l.join(' ')).join('\n')}\n`;
  const file = atTop(place, REGISTRY);
  if (!existsSync(file) || lf(readFileSync(file, 'utf8')) !== registry) {
    writeFileSync(file, registry);
    notes.push(`✓ ${REGISTRY}: ${PACKAGE} ${place.dir}`);
  }
  const hooksPath = posix(git('config', '--get', 'core.hooksPath'));
  if (LEGACY_HOOKS.test(hooksPath)) {
    git('config', 'core.hooksPath', DISPATCH);
    notes.push(`✓ git config core.hooksPath ${hooksPath} → ${DISPATCH} (shared dispatcher)`);
  }
  return notes;
}

/** Problems that keep this project's hooks or CI from running at all (core.hooksPath/workflow location). */
function placeIssues(cfg) {
  const place = repoPlace();
  if (!place) return [];
  const issues = [];
  if (place.prefix && isInstalled() && existsSync(p(CI_CALLER)) && isGenerated(CI_CALLER))
    issues.push(
      `${place.prefix}${CI_CALLER}: GitHub only reads workflows at the repository root → run sync (writes ${posix(relative(atTop(place), p(ciCallerPath(place))))})`,
    );
  // Not set (e.g. CI runners): --ready reports it. Another manager (husky…): gateWarnings/--ready.
  const hooksPath = posix(git('config', '--get', 'core.hooksPath'));
  if (LEGACY_HOOKS.test(hooksPath)) {
    issues.push(
      `core.hooksPath ${hooksPath}: git resolves it from the repository root and 0.2.0 hooks live in ${DISPATCH}/ → run sync`,
    );
  } else if (hooksPath.replace(/\/$/, '') === DISPATCH) {
    const phases = PHASES.filter((ph) => (cfg.hooks?.[ph] ?? []).length);
    for (const ph of phases)
      if (!existsSync(atTop(place, DISPATCH, ph))) issues.push(`${DISPATCH}/${ph} missing → run sync`);
    if (phases.length && !readRegistry(place).some(([pkg, dir]) => pkg === PACKAGE && dir === place.dir))
      issues.push(`${place.dir} not registered in ${REGISTRY}: its hooks never run → run sync`);
  }
  return issues;
}

/** The package's CLI as the dispatcher finds it: <project>/node_modules, then hoisted up to the root. */
function hookBin(place) {
  const rel = `node_modules/${PACKAGE}/bin/aquila.mjs`;
  for (let dir = place.dir; ; dir = posix(dirname(dir))) {
    if (existsSync(atTop(place, dir, rel))) return dir === '.' ? rel : `${dir}/${rel}`;
    if (dir === '.') return null;
  }
}

/** `.aquila/` is shared with sibling packages (aquila-ai for NestJS): never overwrite another one's method. */
export function assertOwnMethod(root = ROOT) {
  const readme = join(root, METHOD, 'README.md');
  if (!existsSync(readme)) return;
  const owner = /^# \.aquila — (\S+) /.exec(readFileSync(readme, 'utf8'))?.[1];
  if (owner && owner !== 'aquila-react-ai') {
    throw new Error(
      `${METHOD}/ belongs to ${owner}: one aquila package per project root — aquila-react-ai would overwrite its method, routers and gates`,
    );
  }
}

/** Copies the method into .aquila/ (overwrites; removes files the package no longer has). */
function syncMethod() {
  const files = methodFiles();
  const want = new Set(files.map(([rel]) => `${METHOD}/${rel}`));
  let changed = 0;
  for (const [rel, text] of files) {
    const path = `${METHOD}/${rel}`;
    if (!existsSync(p(path)) || lf(read(path)) !== lf(text)) {
      mkdirSync(dirname(p(path)), { recursive: true });
      writeFileSync(p(path), text);
      changed++;
    }
  }
  for (const path of listMethod().filter((f) => !want.has(f))) {
    rmSync(p(path));
    changed++;
  }
  return changed
    ? [`✓ ${METHOD}/ — aquila-react-ai ${version()} method (${changed} file(s) updated; commit it)`]
    : [];
}

export function sync() {
  assertOwnMethod();
  const cfg = assertConfig(loadConfig());
  const notes = [];
  const before = JSON.stringify(cfg);
  const lintNote = syncLintGate(cfg);
  if (JSON.stringify(cfg) !== before) writeFileSync(p(CONFIG), `${JSON.stringify(cfg, null, 2)}\n`);
  if (lintNote) notes.push(lintNote);
  notes.push(...syncMethod(), ...syncHooks());
  const items = plan(cfg);
  const wanted = new Set(items.map((i) => i.path));
  // 0.1.0 wrote the workflow inside a subfolder project, where GitHub never reads it.
  if (repoPlace()?.prefix && isGenerated(CI_CALLER)) {
    rmSync(p(CI_CALLER));
    notes.push(`✓ removed ${CI_CALLER} (GitHub reads workflows only at the repository root)`);
  }

  const team = cfg.mode === 'team';
  for (const item of items) {
    const raw = existsSync(p(item.path)) ? read(item.path) : null;
    const current = raw === null ? null : lf(raw);
    let next = item.content;
    let note = `✓ ${item.path}`;
    if (current !== null && item.router) {
      if (BLOCK_RE.test(current)) next = current.replace(BLOCK_RE, item.content);
      else if (!team && git('ls-files', '--error-unmatch', item.path)) {
        // In local mode nothing from aquila-react-ai is versioned: touching a team router would leave it modified.
        notes.push(
          `! ${item.path} is versioned and in local mode I don't touch it — use mode team to let aquila-react-ai manage it`,
        );
        continue;
      } else if (!current.startsWith(`<!-- ${MARK}`)) {
        // Project router: the aquila-react-ai block goes on top and existing content stays intact.
        next = `${item.content}\n${current}`;
        note = `✓ ${item.path}: aquila-react-ai block injected at the top (existing content kept)`;
      }
    } else if (current !== null && !isGenerated(item.path)) {
      notes.push(`✗ ${item.path} exists and was not generated by aquila-react-ai — left untouched`);
      continue;
    }
    if (current === next) continue;
    mkdirSync(dirname(p(item.path)), { recursive: true });
    // Keep the existing file's line endings (a CRLF router doesn't become LF).
    writeFileSync(p(item.path), raw?.includes('\r\n') ? next.replaceAll('\n', '\r\n') : next);
    notes.push(note);
  }

  // Remove generated adapters no longer in the plan (tool turned off, skill removed) and stray skill
  // links in .agents/skills and .claude/skills (never the target's content).
  for (const dir of ['.claude/commands', '.claude/skills', '.agents/skills']) {
    if (!existsSync(p(dir))) continue;
    for (const name of readdirSync(p(dir))) {
      const rel = `${dir}/${name}`;
      if (wanted.has(rel)) continue;
      const target = linkTarget(rel);
      if (target && (isUnder(target, PKG) || isUnder(target, p('docs/ai/skills')))) removeLink(rel);
      else if (isGenerated(rel)) rmSync(p(rel));
      else continue;
      notes.push(`✓ removed ${rel}`);
    }
    if (dir === '.agents/skills' && !readdirSync(p(dir)).length) {
      rmdirSync(p(dir));
      if (!readdirSync(p('.agents')).length) rmdirSync(p('.agents'));
    }
  }
  for (const router of ROUTERS) {
    if (wanted.has(router) || !existsSync(p(router))) continue;
    const current = lf(read(router));
    const rest = BLOCK_RE.test(current)
      ? current.replace(BLOCK_RE, '').replace(/^\n+/, '')
      : current.startsWith(`<!-- ${MARK}`)
        ? ''
        : null;
    if (rest === null) continue;
    if (rest.trim()) writeFileSync(p(router), rest);
    else rmSync(p(router));
    notes.push(`✓ removed ${rest.trim() ? `the aquila-react-ai block from ${router}` : router}`);
  }

  // Settings: aquila-react-ai keys go in when the tool is active and out when it is turned off.
  // The Claude marketplace (package directory) is shared in team: without it a teammate can't install the plugin.
  for (const [file, patch, active] of settingsSpec(cfg)) {
    const note = active ? mergeJson(file, patch) : unmergeJson(file, patch);
    if (note) notes.push(note);
  }
  if (existsSync(p('.claude/commands')) && !readdirSync(p('.claude/commands')).length) {
    rmdirSync(p('.claude/commands'));
  }

  // Method ephemerals (core/workflow.md) are never versioned.
  const excluded = [
    'plan.md',
    'spec.md',
    LOCAL,
    ...items.filter((i) => !i.versioned && !(team && i.router)).map((i) => i.path),
  ];
  // In local mode the VS Code settings are this machine's only; in team the chat.* keys are the team's.
  if (!team && !git('ls-files', '--error-unmatch', '.vscode/settings.json'))
    excluded.push('.vscode/settings.json');
  if (!writeExclude(excluded)) notes.push('! no git repository: nothing was excluded from git');
  if (team) {
    // In team mode the routers, VS Code settings and enabled plugin are versioned: a project
    // .gitignore must not hide them.
    const shared = [...items.filter((i) => i.router).map((i) => i.path)];
    if (cfg.tools.includes('copilot')) shared.push('.vscode/settings.json');
    if (cfg.tools.includes('claude')) shared.push('.claude/settings.json');
    for (const path of shared.filter((f) => git('check-ignore', '--no-index', f))) {
      notes.push(
        `✗ ${path} is in the project's .gitignore, but mode team versions it — remove it from .gitignore`,
      );
    }
  }
  return notes;
}

// ---------------------------------------------------------------- check

function checkAdapters(cfg) {
  const drift = [];
  for (const item of plan(cfg)) {
    const exists = existsSync(p(item.path));
    const current = exists ? lf(read(item.path)) : '';
    // In routers only the aquila-react-ai block counts; the rest belongs to the project. CRLF is no difference.
    const ours = item.router ? (current.match(BLOCK_RE)?.[0] ?? null) : current;
    if (exists && ours !== null && isGenerated(item.path) && ours !== item.content)
      drift.push(`${item.path} out of date`);
    if (cfg.mode === 'team' && item.router && (!exists || ours === null))
      drift.push(`${item.path} ${exists ? 'without the aquila-react-ai block' : 'missing'} (mode: team)`);
  }
  return [...drift, ...settingsDrift(cfg)];
}

/**
 * aquila-react-ai keys missing from the active tools' settings (also in JSONC, which sync doesn't rewrite).
 * In local mode only if the file exists — local settings aren't there in CI.
 */
function settingsDrift(cfg, required = false) {
  const team = cfg.mode === 'team';
  const drift = [];
  for (const [file, patch, active] of settingsSpec(cfg)) {
    if (!active || (!team && !required && !existsSync(p(file)))) continue;
    const parsed = existsSync(p(file)) ? parseJsonc(read(file)) : null;
    if (!parsed || !hasKeys(parsed, patch)) {
      drift.push(`${file} without the aquila-react-ai keys (${Object.keys(patch).join(', ')})`);
    }
  }
  return drift;
}

export function check(args = []) {
  for (const arg of args)
    if (arg !== '--ready') throw new Error(`unknown flag: ${arg} (valid: --ready)`);
  const ready = args.includes('--ready');
  const cfg = loadConfig();
  const config = configValidation(cfg);
  log(
    !config.errors.length,
    `${CONFIG}${config.errors.length ? ` invalid (schema: .aquila/schema/aquila.schema.json):\n  ${config.errors.join('\n  ')}` : ' valid'}`,
  );
  if (config.unknown.length)
    console.log(`! ${CONFIG}: keys outside the schema (typo?): ${config.unknown.join(', ')}`);
  if (config.legacyWhen.length)
    console.log(
      `! ${CONFIG}: text \`when\` in gates ${config.legacyWhen.join(', ')} does not filter execution; migrate to a list of path globs`,
    );
  if (config.errors.length) return 1;
  const { files, broken, over, uncovered } = inspectDocuments({
    root: ROOT,
    cfg,
    walk,
    routers: ROUTERS,
    instructions: INSTRUCTIONS,
    budgets: DEFAULT_BUDGETS,
    frontmatter,
  });
  log(
    !broken.length,
    `links: ${files} files${broken.length ? `, ${broken.length} broken:\n  ${broken.join('\n  ')}` : ''}`,
  );
  log(
    !over.length,
    `budgets${over.length ? ` over the limit (move detail to references/ or docs/):\n  ${over.join('\n  ')}` : ''}`,
  );
  const drift = [...methodDrift(), ...checkAdapters(cfg)];
  log(
    !drift.length,
    `adapters${drift.length ? ` — run \`npx aquila-react-ai sync\`:\n  ${drift.join('\n  ')}` : ' in sync'}`,
  );
  if (!ready) for (const warning of docWarnings(ROOT)) console.log(warning);
  if (uncovered.length)
    console.log(
      `! ${uncovered.length} file(s) without per-folder instructions (warning):\n  ${uncovered.slice(0, 20).join('\n  ')}`,
    );
  const place = placeIssues(cfg);
  if (place.length) log(false, `hooks/CI location:\n  ${place.join('\n  ')}`);
  let failed = broken.length > 0 || over.length > 0 || drift.length > 0 || place.length > 0;
  if (ready) {
    const issues = readinessIssues(ROOT, cfg);
    for (const item of plan(cfg)) {
      if (!existsSync(p(item.path))) issues.push(`${item.path} missing → run sync`);
      else if (item.router && !BLOCK_RE.test(lf(read(item.path))))
        issues.push(`${item.path} without the aquila-react-ai block → resolve the mode and run sync`);
    }
    if (!isInstalled())
      issues.push('aquila-react-ai is not in package.json → npm i -D aquila-react-ai');
    const caller = ciCallerPath();
    if (existsSync(p(caller)) && !isGenerated(caller))
      issues.push(
        `${caller}: manual CI integration not verified → review that your pipeline runs check and gate ci; plain check does not require the generated workflow`,
      );
    issues.push(...settingsDrift(cfg, true));
    // core.hooksPath is relative to the repository root; --git-path to the current folder.
    const configured = git('config', '--get', 'core.hooksPath');
    issues.push(
      ...(configured
        ? hookIssues(resolve(ROOT, git('rev-parse', '--show-cdup') || '.'), cfg, configured)
        : hookIssues(ROOT, cfg, git('rev-parse', '--git-path', 'hooks'))),
    );
    if (cfg.tools.includes('claude')) {
      const installed = claudePluginInstalled();
      if (installed !== true)
        issues.push(
          `Claude Code plugin ${installed === null ? 'not verified (CLI unavailable or failed)' : 'missing'} → install aquila@aquila-react-ai on this machine`,
        );
    }
    log(
      !issues.length && !failed,
      issues.length || failed
        ? `readiness blocked${issues.length ? `:\n  ${issues.join('\n  ')}` : ' — fix the failures above'}`
        : 'technical readiness verified — review the docs for accuracy; gates were not run and remote CI was not checked',
    );
    failed ||= issues.length > 0;
  }
  return failed ? 1 : 0;
}

