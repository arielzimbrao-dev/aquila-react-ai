/** Normalized target of a symlink/junction, or null if not a link. */
function linkTarget(path) {
  try {
    if (!lstatSync(p(path)).isSymbolicLink()) return null;
    return norm(resolve(dirname(p(path)), readlinkSync(p(path))));
  } catch {
    return null;
  }
}

/** Removes only the link (never the target's content). */
function removeLink(path) {
  try {
    unlinkSync(p(path));
  } catch {
    rmdirSync(p(path));
  }
}

function writeExclude(paths) {
  const file = git('rev-parse', '--git-path', 'info/exclude');
  if (!file) return false;
  const full = resolve(ROOT, file);
  const current = existsSync(full) ? readFileSync(full, 'utf8') : '';
  // info/exclude is anchored at the repository root, not at the project: prefix the project folder.
  const prefix = git('rev-parse', '--show-prefix');
  const block = `# >>> aquila-react-ai (generated; do not edit)\n${paths.map((x) => `/${prefix}${x}`).join('\n')}\n# <<< aquila-react-ai\n`;
  const re = /# >>> aquila-react-ai[\s\S]*?# <<< aquila-react-ai\n?/;
  const next = re.test(current)
    ? current.replace(re, block)
    : `${current}${current && !current.endsWith('\n') ? '\n' : ''}${block}`;
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, next);
  return true;
}

/**
 * JSON with comments and trailing commas (JSONC, the VS Code settings format) → object. Respects
 * strings; returns null if it still isn't JSON.
 */
export function parseJsonc(text) {
  let out = '';
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === '"') {
      const end = /"(?:[^"\\]|\\.)*"/y;
      end.lastIndex = i;
      const m = end.exec(text);
      if (!m) return null;
      out += m[0];
      i += m[0].length - 1;
    } else if (c === '/' && text[i + 1] === '/') {
      while (i < text.length && text[i] !== '\n') i++;
      out += '\n';
    } else if (c === '/' && text[i + 1] === '*') {
      const close = text.indexOf('*/', i + 2);
      i = close < 0 ? text.length : close + 1;
    } else out += c;
  }
  try {
    return JSON.parse(out.replaceAll(/,(\s*[}\]])/g, '$1'));
  } catch {
    return null;
  }
}

/** Are the `patch` keys (one level deep) already in `current`? */
const hasKeys = (current, patch) =>
  Object.entries(patch).every(([k, v]) =>
    typeof v === 'object'
      ? Object.entries(v).every(
          ([kk, vv]) => JSON.stringify(current?.[k]?.[kk]) === JSON.stringify(vv),
        )
      : current?.[k] === v,
  );

/**
 * Adds aquila-react-ai keys to a settings JSON. A file with comments (JSONC) is never rewritten — the comments
 * would be lost: it is only checked and, if something is missing, the note says what to add.
 */
function mergeJson(file, patch) {
  let current = {};
  if (existsSync(p(file))) {
    const raw = read(file);
    try {
      current = JSON.parse(raw);
    } catch {
      const parsed = parseJsonc(raw);
      if (parsed && hasKeys(parsed, patch)) return null;
      return `✗ ${file} has comments (JSONC) and I won't rewrite it — add by hand: ${JSON.stringify(patch)}`;
    }
  }
  const next = { ...current };
  for (const [k, v] of Object.entries(patch))
    next[k] = typeof v === 'object' ? { ...current[k], ...v } : v;
  if (JSON.stringify(next) === JSON.stringify(current)) return null;
  mkdirSync(dirname(p(file)), { recursive: true });
  writeFileSync(p(file), `${JSON.stringify(next, null, 2)}\n`);
  return `✓ ${file} (aquila-react-ai keys)`;
}

/** Removes from a settings JSON the keys aquila-react-ai put there (tool turned off). */
function unmergeJson(file, patch) {
  if (!existsSync(p(file))) return null;
  let current;
  try {
    current = JSON.parse(read(file));
  } catch {
    return null; // JSONC: aquila-react-ai never wrote it, it won't rewrite it now
  }
  const next = { ...current };
  for (const [k, v] of Object.entries(patch)) {
    if (typeof v !== 'object' || typeof next[k] !== 'object') continue;
    next[k] = { ...next[k] };
    for (const kk of Object.keys(v)) delete next[k][kk];
    if (!Object.keys(next[k]).length) delete next[k];
  }
  if (JSON.stringify(next) === JSON.stringify(current)) return null;
  if (Object.keys(next).length) writeFileSync(p(file), `${JSON.stringify(next, null, 2)}\n`);
  else rmSync(p(file));
  return `✓ removed aquila-react-ai keys from ${file}`;
}

