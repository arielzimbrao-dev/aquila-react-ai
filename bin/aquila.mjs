/** Definition of done with the project's real commands (saves opening done.md + aquila.json each task). */
function doneSection(cfg) {
  const lines = (cfg.hooks?.ci ?? Object.keys(cfg.gates ?? {}))
    .map((name) => {
      const g = cfg.gates?.[name];
      if (!g) return null;
      const cmd = typeof g === 'string' ? g : g.cmd;
      const when =
        typeof g === 'object' && Array.isArray(g.when)
          ? ` — CI only when these change: ${g.when.join(', ')}`
          : typeof g === 'object' && g.when
            ? ` — legacy note (does not condition execution): ${g.when}`
            : '';
      return `- [ ] ${name}: \`${cmd}\`${when}`;
    })
    .filter(Boolean);
  const { enforced, ...limits } = cfg.coverage ?? {};
  const coverage = Object.entries(limits)
    .map(([k, v]) => `${k} ≥ ${v}`)
    .join(', ');
  // Only say "enforced" when a coverage gate fails below the threshold (aquila.json → coverage.enforced).
  const applied = cfg.gates?.coverage && enforced !== false;
  const how = applied
    ? 'enforced by the `coverage` command'
    : 'target — no gate enforces it; set the threshold in the coverage tool';
  return [
    '**Done** (gates with a `when` list only run in CI when matching files change; the other listed gates always run; local hooks do not filter by `when`; every executed gate must pass; rest of the checklist in `.aquila/core/done.md`):',
    '',
    ...(lines.length
      ? lines
      : ['- [ ] (no gates defined — define them in `docs/ai/aquila.json` → `gates`)']),
    ...(coverage ? [`- Project coverage: ${coverage} (${how}).`] : []),
  ].join('\n');
}

