/** init flags in the order of the `/aquila-init` questions → key in opts. */
const INIT_FLAGS = [
  ['lang', 'lang'],
  ['tools', 'tools'],
  ['token-limit', 'tokenLimit'],
  ['mode', 'mode'],
  ['lint', 'lint'],
  ['pr-max-files', 'prMaxFiles'],
];
export const LANGUAGES = ['en', 'pt-BR', 'pt-PT'];

export function parseOpts(args) {
  const allowedTools = ['copilot', 'claude', 'codex'];
  const opts = {};
  for (const arg of args) {
    const [k, ...rest] = arg.replace(/^--/, '').split('=');
    const v = rest.join('=');
    if (!INIT_FLAGS.some(([flag]) => flag === k))
      throw new Error(
        `unknown flag: ${arg} (valid: ${INIT_FLAGS.map(([f]) => `--${f}`).join(' ')})`,
      );
    if (!v) throw new Error(`--${k} needs a value (--${k}=…)`);
    if (k === 'lang') {
      if (!LANGUAGES.includes(v)) throw new Error(`--lang is ${LANGUAGES.join(', ')}`);
      opts.lang = v;
    }
    if (k === 'token-limit') {
      opts.tokenLimit = v === 'none' ? null : Number(v);
      if (opts.tokenLimit !== null && (!Number.isFinite(opts.tokenLimit) || opts.tokenLimit <= 0))
        throw new Error('--token-limit is a number of tokens > 0 or none');
    }
    if (k === 'tools') {
      const tools = v.split(',');
      if (
        tools.some((tool) => !allowedTools.includes(tool)) ||
        new Set(tools).size !== tools.length
      ) {
        throw new Error(`--tools accepts unique tools: ${allowedTools.join(', ')}`);
      }
      opts.tools = tools;
    }
    if (k === 'mode') {
      if (!['local', 'team'].includes(v)) throw new Error('--mode is local or team');
      opts.mode = v;
    }
    if (k === 'lint') {
      if (!['off', 'standard', 'high'].includes(v))
        throw new Error('--lint is off, standard or high');
      opts.lint = v;
    }
    if (k === 'pr-max-files') {
      opts.prMaxFiles = Number(v);
      if (!Number.isInteger(opts.prMaxFiles) || opts.prMaxFiles < 1)
        throw new Error('--pr-max-files is an integer number of files > 0');
    }
  }
  return opts;
}

export function nodeVersionSupported(v = process.versions.node) {
  const major = Number.parseInt(v.split('.')[0], 10);
  return Number.isInteger(major) && major >= 22;
}

