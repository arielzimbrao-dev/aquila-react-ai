/**
 * Where the project sits in its git repository: `prefix` ('frontend/', '' at the root), `up` ('../') and
 * `dir` ('frontend', '.' at the root). null outside git.
 */
function repoPlace() {
  if (!git('rev-parse', '--git-dir')) return null;
  const prefix = git('rev-parse', '--show-prefix');
  return { prefix, up: git('rev-parse', '--show-cdup'), dir: prefix.replace(/\/$/, '') || '.' };
}
const atTop = (place, ...parts) => p(place.up, ...parts);

function walk(dir, pick = () => true) {
  const full = p(dir);
  if (!existsSync(full) || !statSync(full).isDirectory()) return [];
  return readdirSync(full).flatMap((name) => {
    const rel = posix(join(dir, name));
    if (['node_modules', '.git', 'dist', 'coverage'].includes(name)) return [];
    if (lstatSync(p(rel)).isSymbolicLink()) return [];
    return statSync(p(rel)).isDirectory() ? walk(rel, pick) : pick(rel) ? [rel] : [];
  });
}

/** Simple YAML frontmatter: `key: value` and `>-`/`>`/`|` blocks (indented lines joined). */
export function frontmatter(text) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  if (!m) return {};
  const out = {};
  let key = null;
  for (const line of m[1].split(/\r?\n/)) {
    const kv = /^(\w[\w-]*):\s*(.*)$/.exec(line);
    if (kv) {
      key = /^[>|]-?$/.test(kv[2]) ? kv[1] : null;
      out[kv[1]] = key ? '' : kv[2].replace(/^['"]|['"]$/g, '');
    } else if (key && /^\s+\S/.test(line)) {
      out[key] = `${out[key]} ${line.trim()}`.trim();
    }
  }
  return out;
}

