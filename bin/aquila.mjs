export function init(opts = {}) {
  assertOwnMethod();
  const done = [];
  const configured = existsSync(p(CONFIG));
  const existingConfig = configured ? assertConfig(loadConfig()) : null;
  if (!configured) {
    const preset = detectStack(ROOT);
    if (!preset.detected)
      done.push('! react not found in package.json — aquila-react-ai targets React projects');
    const cfg = defaultConfig(ROOT, preset, opts, {
      budgets: DEFAULT_BUDGETS,
      configPaths: DEFAULT_CONFIG_PATHS,
    });
    mkdirSync(p('docs/ai'), { recursive: true });
    writeFileSync(p(CONFIG), `${JSON.stringify(cfg, null, 2)}\n`);
    done.push(`✓ ${CONFIG} (stack ${preset.name}; confirm the gates)`);
  } else if (opts.lang || opts.tools || opts.mode || opts.lint || opts.prMaxFiles) {
    // Re-running init with the dev's answers updates the existing config.
    const cfg = existingConfig;
    if (opts.lang) cfg.language = { ...cfg.language, docs: opts.lang, answers: opts.lang };
    if (opts.tools) cfg.tools = opts.tools;
    if (opts.mode) cfg.mode = opts.mode;
    if (opts.lint) cfg.lint = { ...cfg.lint, level: opts.lint };
    if (opts.prMaxFiles) cfg.review = { ...cfg.review, prMaxFiles: opts.prMaxFiles };
    writeFileSync(p(CONFIG), `${JSON.stringify(cfg, null, 2)}\n`);
    done.push(
      `✓ ${CONFIG} updated (language, tools, mode, lint ${cfg.lint?.level} and PR ≤ ${prMaxFiles(cfg)} files)`,
    );
  }
  if ('tokenLimit' in opts) {
    writeFileSync(p(LOCAL), `${JSON.stringify({ tokenLimit: opts.tokenLimit }, null, 2)}\n`);
    const what = opts.tokenLimit
      ? `monthly limit ${opts.tokenLimit} tokens`
      : 'no limit — no usage alert';
    done.push(`✓ ${LOCAL} (outside git): ${what}`);
  }
  const missing = INIT_FLAGS.filter(([, key]) => !(key in opts)).map(([flag]) => flag);
  if (missing.length)
    done.push(
      configured
        ? `ℹ without --${missing.join(', --')}: existing values kept`
        : `! without --${missing.join(', --')}: defaults used — ask the dev and repeat`,
    );
  const templates = join(PKG, 'templates');
  const copyMissing = (from, to) => {
    for (const name of readdirSync(from)) {
      const src = join(from, name);
      const dest = join(to, name);
      if (statSync(src).isDirectory()) copyMissing(src, dest);
      else if (!existsSync(p(dest))) {
        mkdirSync(dirname(p(dest)), { recursive: true });
        cpSync(src, p(dest));
        done.push(`✓ ${posix(dest)}`);
      }
    }
  };
  copyMissing(join(templates, 'docs'), 'docs');
  copyMissing(join(templates, 'github'), '.github');
  // The CI caller is an adapter: sync writes it (only when package.json declares aquila-react-ai).
  if (!isInstalled())
    done.push(
      '! aquila-react-ai is not in package.json: no CI workflow and hooks may break → npm i -D aquila-react-ai',
    );
  done.push(...sync());

  const place = repoPlace();
  // sync already moved a 0.1.0 aquila hooksPath to the dispatcher.
  const hooksPath = posix(git('config', '--get', 'core.hooksPath')).replace(/\/$/, '');
  // Hooks already in .git/hooks (lefthook, pre-commit, hand-written) would stop running if core.hooksPath
  // pointed to aquila-react-ai: in that case don't set it and say how to integrate.
  const hooksDir = place ? resolve(ROOT, git('rev-parse', '--git-path', 'hooks')) : '';
  const existing =
    place && existsSync(hooksDir) ? readdirSync(hooksDir).filter((n) => !n.endsWith('.sample')) : [];
  const call = `\`${place?.prefix ? `cd ${place.dir} && ` : ''}npx aquila-react-ai gate pre-commit|pre-push\``;
  if (!place) {
    done.push('! no git repository: git hooks not set');
  } else if (!hooksPath && existing.length) {
    done.push(
      `! git hooks already exist in .git/hooks (${existing.join(', ')}) — not replaced; call ${call} from them`,
    );
  } else if (!hooksPath) {
    git('config', 'core.hooksPath', DISPATCH);
    done.push(`✓ git config core.hooksPath = ${DISPATCH} (shared dispatcher at the repository root)`);
  } else if (hooksPath !== DISPATCH) {
    done.push(`! a hook manager already exists (${hooksPath}) — call ${call} from it`);
  }
  const cfg = loadConfig();
  done.push(
    cfg.mode === 'team'
      ? 'ℹ team mode: commit the managed routers and settings; each dev still sets the hooks with init'
      : 'ℹ local mode: generated routers and settings are local; each dev runs init; cloud agents need team',
  );
  if (!(cfg.hooks?.ci ?? []).length) {
    done.push(`! no CI gates detected — define them in ${CONFIG} → gates and hooks.ci`);
  }
  if (cfg.lint?.pending) {
    done.push(
      `! lint-aquila left out of the gates until the engine is installed: ${cfg.lint.pending} — after installing run \`npx aquila-react-ai sync\``,
    );
  }
  done.push(`ℹ ${lintSummary(cfg.lint?.level ?? 'off', cfg.lint?.engine ?? null, ROOT)}`);

  console.log(done.join('\n'));
  console.log(
    '\nCLI: technical install and templates; /aquila-init completes the setup with /aquila-docs (CONTEXT, golden, instructions, C4), CI/hooks integration and validation. Resolve the warnings before starting a plan. Validate this machine with `npx aquila-react-ai check --ready` and run `npx aquila-react-ai gate ci`.',
  );
  return 0;
}

function claudePluginInstalled() {
  // On Windows `claude` is a .cmd and needs the shell; command as a single string (DEP0190).
  const r = spawnSync('claude plugin list', { encoding: 'utf8', shell: true, timeout: 10000 });
  if (r.status !== 0) return null;
  return /aquila@aquila-react-ai/.test(r.stdout);
}

const PHASES = ['pre-commit', 'pre-push'];

/** Gates that never run and hooks from another manager (husky…) that don't go through `aquila-react-ai gate`. */
function gateWarnings(cfg, hooksPath) {
  const out = [];
  const ci = cfg.hooks?.ci ?? Object.keys(cfg.gates ?? {});
  const phased = new Set([...ci, ...PHASES.flatMap((ph) => cfg.hooks?.[ph] ?? [])]);
  for (const name of Object.keys(cfg.gates ?? {}).filter((n) => !phased.has(n)))
    out.push(`! gate ${name} in no phase (hooks.pre-commit/pre-push/ci): never runs`);
  if (!hooksPath || posix(hooksPath).replace(/\/$/, '') === DISPATCH) return out;
  // husky v9 sets `.husky/_` (generated wrappers); the project's scripts are in `.husky/`.
  const dir = hooksPath.replace(/[\\/]_[\\/]?$/, '');
  for (const phase of PHASES) {
    // core.hooksPath is resolved from the repository root.
    const file = p(git('rev-parse', '--show-cdup'), dir, phase);
    if (!existsSync(file)) continue;
    if (!/(?:aquila\.mjs|aquila-react-ai)\s+gate/.test(readFileSync(file, 'utf8')))
      out.push(
        `! ${posix(join(dir, phase))} does not call \`npx aquila-react-ai gate ${phase}\`: what runs there is not hooks.${phase} from ${CONFIG}`,
      );
  }
  return out;
}

